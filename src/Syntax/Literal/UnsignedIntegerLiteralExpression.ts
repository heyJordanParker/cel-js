import { Span } from '../../Span/Span.js'
import { ExpressionKind } from '../ExpressionKind.js'
import type { Node } from '../Node.js'

export class UnsignedIntegerLiteralExpression implements Node {
  readonly kind = ExpressionKind.UIntLiteral

  constructor(
    readonly value: number | string,
    readonly raw: string,
    readonly span: Span,
  ) {}

  getChildren(): Node[] {
    return []
  }

  getSpan(): Span {
    return this.span
  }
}
